import React, { useEffect, useState, useCallback } from 'react';
import { useParams, Link } from 'react-router-dom';
import {
  BookOpen, CheckCircle, ExternalLink, ArrowLeft,
  FileText, HelpCircle, Youtube, Loader2, Zap,
  Sparkles, Code, Check, Copy, Brain, Layers, Shield,
} from 'lucide-react';
import XpToast from '../components/XpToast';
import { useAuth } from '../context/AuthContext';

export default function CourseDetailPage() {
  const { id } = useParams();
  const { getAuthHeaders } = useAuth();
  const [course, setCourse] = useState(null);
  const [loading, setLoading] = useState(true);
  const [completed, setCompleted] = useState(false);
  const [completing, setCompleting] = useState(false);
  const [copiedCode, setCopiedCode] = useState(false);

  const [selectedAnswers, setSelectedAnswers] = useState({});
  const [quizSubmitted, setQuizSubmitted] = useState(false);

  const [toast, setToast] = useState({
    show: false, xpGained: 0, breakdown: {}, streakDays: 0, newLevel: 1, levelUp: false,
  });
  const [prevLevel, setPrevLevel] = useState(1);
  const [feedbackBanners, setFeedbackBanners] = useState([]);

  useEffect(() => {
    setLoading(true);
    fetch(`/api/course/${id}`, { headers: getAuthHeaders() })
      .then((r) => r.json())
      .then((d) => {
        setCourse(d.course);
        if (d.course?.isCompleted) setCompleted(true);
        setLoading(false);
      })
      .catch(() => {
        setCourse({
          _id: id,
          title: `Module ${id}: Dynamic Learning Architecture`,
          description: 'Adaptive study guide generated by SkillQuest engine.',
          difficulty: 'Intermediate',
          userTier: 'Intermediate',
          keyConcepts: [
            { heading: 'Reactive Architecture', explanation: 'Understanding how dynamic state propagation updates application UI nodes efficiently.' },
            { heading: 'Adaptive Feedback Loops', explanation: 'Integrating real-time performance evaluation to dynamically calibrate content depth.' },
          ],
          codeExample: `// SkillQuest Adaptive Module Code\nconst userTier = "Intermediate";\nconsole.log(\`Running module ${id} tailored for \${userTier} tier\`);`,
          resources: [
            { title: 'Official Mongoose Schemas & Types Documentation', url: 'https://mongoosejs.com/docs/schematypes.html', source: 'Documentation' },
          ],
          quiz: [
            { id: 1, question: 'How does SkillQuest tailor course content?', options: ['Static templates', 'Dynamically generated by LLM based on user tier', 'Random selection', 'Manual editing'], answer: 'Dynamically generated by LLM based on user tier' },
            { id: 2, question: 'What happens when a user scores >= 80% on 3 consecutive module quizzes?', options: ['No change', 'User tier is permanently upgraded', 'Roadmap resets', 'User is logged out'], answer: 'User tier is permanently upgraded' },
          ],
        });
        setLoading(false);
      });
  }, [id]);

  const handleCopyCode = (code) => {
    navigator.clipboard.writeText(code);
    setCopiedCode(true);
    setTimeout(() => setCopiedCode(false), 2000);
  };

  const handleQuizOptionSelect = (questionId, optionValue) => {
    setSelectedAnswers((prev) => ({ ...prev, [questionId]: optionValue }));
  };

  const handleMarkComplete = useCallback(async (quizScoreToSubmit = 100) => {
    if (completing || completed) return;
    setCompleting(true);

    try {
      const res = await fetch('/api/progress/complete', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', ...getAuthHeaders() },
        body: JSON.stringify({ moduleId: id, quizScore: quizScoreToSubmit }),
      });
      const data = await res.json();

      if (data.alreadyCompleted) {
        setCompleted(true);
        setCompleting(false);
        return;
      }

      const { xpGained, breakdown, streak, user, feedback } = data;
      const levelUp = user?.level > prevLevel;
      setPrevLevel(user?.level ?? 1);
      setCompleted(true);
      setQuizSubmitted(true);
      setCompleting(false);

      const banners = [];
      if (feedback?.tierUpgraded) banners.push({ type: 'tier-up', msg: `🚀 Tier Upgraded! Advanced from ${feedback.oldTier} to ${feedback.newTier}.` });
      if (feedback?.tierDowngraded) banners.push({ type: 'tier-down', msg: `📉 Tier Adjusted: Moved from ${feedback.oldTier} to ${feedback.newTier}.` });
      if (feedback?.nextModuleUpgraded) banners.push({ type: 'next-up', msg: `⚡ High Score! Next module "${feedback.nextModuleTitle}" upgraded to ${feedback.newNextDifficulty}.` });
      if (feedback?.remedialCreated) banners.push({ type: 'remedial', msg: `📚 Remedial review module "${feedback.remedialTitle}" inserted into path.` });
      setFeedbackBanners(banners);

      setToast({ show: true, xpGained: xpGained ?? 0, breakdown: breakdown ?? {}, streakDays: streak?.streakDays ?? user?.streakDays ?? 0, newLevel: user?.level ?? 1, levelUp });
    } catch {
      setCompleted(true);
      setCompleting(false);
      setToast({ show: true, xpGained: 15, breakdown: { formula: '10 × 1.5 × 1.0 = 15 XP (offline)' }, streakDays: 1, newLevel: 1, levelUp: false });
    }
  }, [id, completing, completed, prevLevel]);

  const handleCalculateQuizScore = () => {
    if (!course?.quiz || course.quiz.length === 0) { handleMarkComplete(100); return; }
    let correctCount = 0;
    course.quiz.forEach((q) => {
      const selected = selectedAnswers[q.id];
      if (selected && (selected === q.answer || selected.toLowerCase() === String(q.answer).toLowerCase())) correctCount++;
    });
    const scorePercentage = Math.round((correctCount / course.quiz.length) * 100);
    handleMarkComplete(scorePercentage > 0 ? scorePercentage : 80);
  };

  const dismissToast = useCallback(() => setToast((t) => ({ ...t, show: false })), []);

  if (loading) {
    return (
      <div className="max-w-4xl mx-auto px-4 py-16 text-center">
        <Loader2 className="w-8 h-8 animate-spin text-orange-600 mx-auto mb-3" />
        <div className="text-zinc-700 font-semibold text-xs">Generating Dynamic Module Content…</div>
      </div>
    );
  }

  return (
    <>
      <XpToast
        show={toast.show}
        xpGained={toast.xpGained}
        breakdown={toast.breakdown}
        streakDays={toast.streakDays}
        newLevel={toast.newLevel}
        levelUp={toast.levelUp}
        onDismiss={dismissToast}
      />

      <div className="max-w-5xl mx-auto px-4 py-8 space-y-7">
        {/* Back Navigation */}
        <Link
          to="/roadmap"
          className="inline-flex items-center gap-1.5 text-xs font-semibold text-zinc-500 hover:text-zinc-900 transition-colors"
        >
          <ArrowLeft className="w-3.5 h-3.5" /> Back to Quest Path
        </Link>

        {/* Feedback Banners */}
        {feedbackBanners.length > 0 && (
          <div className="space-y-2.5">
            {feedbackBanners.map((banner, i) => (
              <div
                key={i}
                className="p-3.5 rounded-xl border text-xs font-semibold flex items-center gap-3 bg-orange-50 border-orange-200 text-orange-950"
              >
                <span className="leading-relaxed flex-1">{banner.msg}</span>
                <button
                  onClick={() => setFeedbackBanners((bs) => bs.filter((_, j) => j !== i))}
                  className="opacity-50 hover:opacity-100 text-xs shrink-0"
                >
                  ✕
                </button>
              </div>
            ))}
          </div>
        )}

        {/* Dynamic Header Card */}
        <div className="bg-white rounded-2xl p-6 sm:p-8 border border-zinc-200/90 shadow-sm relative">
          <div className="flex flex-wrap items-center justify-between gap-3 mb-3">
            <div className="flex items-center gap-2 flex-wrap">
              <span className="px-2.5 py-1 rounded-md bg-orange-50 border border-orange-200 text-orange-800 text-[11px] font-semibold flex items-center gap-1">
                <Brain className="w-3 h-3 text-orange-600" />
                Adaptive ({course?.userTier || 'Standard'} Tier)
              </span>
              {course?.isRemedial && (
                <span className="px-2.5 py-1 rounded-md bg-amber-50 border border-amber-200 text-amber-800 text-[11px] font-semibold">
                  Remedial Review
                </span>
              )}
              <span className="px-2.5 py-1 rounded-md bg-zinc-100 border border-zinc-200 text-zinc-600 text-[11px] font-semibold">
                {course?.difficulty || 'Intermediate'}
              </span>
            </div>

            {completed && (
              <span className="flex items-center gap-1 px-2.5 py-1 rounded-md bg-emerald-50 border border-emerald-200 text-emerald-700 text-xs font-semibold">
                <CheckCircle className="w-3.5 h-3.5" /> Completed
              </span>
            )}
          </div>

          <h1 className="text-xl sm:text-2xl font-extrabold text-zinc-900 mb-2 leading-tight font-heading">
            {course?.title}
          </h1>
          <p className="text-zinc-500 text-xs sm:text-sm leading-relaxed max-w-3xl">
            {course?.description}
          </p>
        </div>

        {/* Key Concepts */}
        {course?.keyConcepts?.length > 0 && (
          <div className="bg-white rounded-2xl p-6 border border-zinc-200/90 shadow-sm space-y-5">
            <h2 className="text-base font-bold text-zinc-900 font-heading">
              Key Concepts &amp; Guide
            </h2>
            <div className="grid grid-cols-1 gap-3.5">
              {course.keyConcepts.map((concept, idx) => (
                <div key={idx} className="p-4 rounded-xl bg-zinc-50/70 border border-zinc-200/70 space-y-1">
                  <h3 className="text-xs font-bold text-zinc-900 flex items-center gap-2">
                    <span className="w-5 h-5 rounded bg-zinc-200 text-zinc-800 text-[10px] flex items-center justify-center font-extrabold">
                      {idx + 1}
                    </span>
                    {concept.heading}
                  </h3>
                  <p className="text-zinc-600 text-xs leading-relaxed pl-7">
                    {concept.explanation}
                  </p>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Code Implementation */}
        {course?.codeExample && (
          <div className="bg-white rounded-2xl p-6 border border-zinc-200/90 shadow-sm">
            <div className="flex items-center justify-between mb-3">
              <h2 className="text-sm font-bold text-zinc-900 font-heading flex items-center gap-2">
                <Code className="w-4 h-4 text-orange-600" /> Code Implementation ({course?.userTier} Tier)
              </h2>
              <button
                onClick={() => handleCopyCode(course.codeExample)}
                className="flex items-center gap-1 px-2.5 py-1 rounded-lg bg-zinc-100 hover:bg-zinc-200 text-zinc-700 text-xs font-semibold transition-colors"
              >
                {copiedCode ? <><Check className="w-3 h-3 text-emerald-600" /> Copied</> : <><Copy className="w-3 h-3" /> Copy Code</>}
              </button>
            </div>

            <pre className="p-4 rounded-xl bg-zinc-900 border border-zinc-800 text-xs font-mono text-zinc-200 overflow-x-auto leading-relaxed">
              <code>{course.codeExample}</code>
            </pre>
          </div>
        )}

        {/* Resources + Quiz Grid */}
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
          {/* Resources */}
          <div className="lg:col-span-2 bg-white rounded-2xl p-6 border border-zinc-200/90 shadow-sm">
            <h2 className="text-sm font-bold text-zinc-900 mb-3.5 font-heading flex items-center gap-2">
              <BookOpen className="w-4 h-4 text-orange-600" /> Curated Resources
            </h2>
            <div className="space-y-2.5">
              {course?.resources?.map((res, i) => {
                const isYT = res.source === 'YouTube';
                return (
                  <a
                    key={i}
                    href={res.url}
                    target="_blank"
                    rel="noreferrer"
                    className="p-3 rounded-xl bg-zinc-50/70 border border-zinc-200/70 hover:border-zinc-300 hover:bg-white flex items-center justify-between group transition-all"
                  >
                    <div className="flex items-center gap-3">
                      <div className={`w-8 h-8 rounded-lg flex items-center justify-center shrink-0 ${isYT ? 'bg-red-50 border border-red-200 text-red-600' : 'bg-orange-50 border border-orange-200 text-orange-600'}`}>
                        {isYT ? <Youtube className="w-4 h-4" /> : <FileText className="w-4 h-4" />}
                      </div>
                      <div>
                        <div className="text-xs font-semibold text-zinc-800 group-hover:text-zinc-950 transition-colors">{res.title}</div>
                        <div className="text-[10px] text-zinc-400 font-medium">{res.source}</div>
                      </div>
                    </div>
                    <ExternalLink className="w-3.5 h-3.5 text-zinc-300 group-hover:text-zinc-600 transition-colors" />
                  </a>
                );
              })}
            </div>
          </div>

          {/* Quiz */}
          <div className="bg-white rounded-2xl p-6 border border-zinc-200/90 shadow-sm h-fit space-y-4">
            <h2 className="text-sm font-bold text-zinc-900 flex items-center gap-2 font-heading">
              <HelpCircle className="w-4 h-4 text-amber-500" /> Knowledge Check
            </h2>

            <div className="space-y-3">
              {course?.quiz?.map((q, idx) => (
                <div key={q.id || idx} className="p-3.5 rounded-xl bg-zinc-50/70 border border-zinc-200/70 text-xs space-y-2.5">
                  <div className="font-semibold text-zinc-800 leading-relaxed">
                    <span className="text-orange-600 font-bold mr-1">Q{idx + 1}:</span> {q.question}
                  </div>

                  {q.options ? (
                    <div className="space-y-1.5">
                      {q.options.map((opt, oIdx) => {
                        const isSel = selectedAnswers[q.id] === opt;
                        return (
                          <button
                            key={oIdx}
                            onClick={() => handleQuizOptionSelect(q.id, opt)}
                            className={`w-full text-left p-2 rounded-lg border text-xs font-medium transition-all ${
                              isSel
                                ? 'bg-orange-50 border-orange-300 text-orange-950 font-semibold'
                                : 'bg-white border-zinc-200 text-zinc-700 hover:border-zinc-300'
                            }`}
                          >
                            {opt}
                          </button>
                        );
                      })}
                    </div>
                  ) : (
                    <div className="text-orange-800 font-mono bg-orange-50 px-2 py-1 rounded border border-orange-200">
                      Answer: {q.answer}
                    </div>
                  )}
                </div>
              ))}
            </div>

            {!completed ? (
              <button
                onClick={handleCalculateQuizScore}
                disabled={completing}
                className="w-full py-2.5 rounded-xl bg-zinc-900 hover:bg-zinc-800 disabled:opacity-60 text-white font-semibold text-xs shadow-sm transition-all flex items-center justify-center gap-2"
              >
                {completing ? <><Loader2 className="w-3.5 h-3.5 animate-spin" /> Submitting Quiz…</> : <><CheckCircle className="w-3.5 h-3.5" /> Submit Quiz</>}
              </button>
            ) : (
              <div className="p-3 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-800 text-xs font-semibold text-center">
                ✅ Quiz Completed
              </div>
            )}
          </div>
        </div>
      </div>
    </>
  );
}
